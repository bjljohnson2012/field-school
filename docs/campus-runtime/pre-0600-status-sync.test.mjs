import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import test from "node:test";

const here = dirname(fileURLToPath(import.meta.url));
const wave5 = readFileSync(join(here, "WAVE5.md"), "utf8");
const campus = readFileSync(join(here, "STATUS.md"), "utf8");
const stub = readFileSync(join(here, "..", "prelaunch", "STATUS.md"), "utf8");
const gate = readFileSync(join(here, "..", "prelaunch", "LAUNCH_GATE.md"), "utf8");

test("pre-0600 sync pins AudioBed, Wave3 LIVE, karaoke, letterbox, master dest; launch CLOSED 0/8", () => {
  assert.match(wave5, /2026-09-20 overnight close-sync/);
  assert.match(wave5, /2026-09-20 pre-0600 status sync/);
  assert.match(wave5, /lesson-spine-audiobed-encode\/2026-09-20/);
  assert.match(wave5, /9f89f9a9a89670c6bac382d1f97b3d7283c47a8a06e7c2c069314bf59ea2d59f/);
  assert.match(wave5, /same as karaoke gold when AudioBed volume 0/);
  assert.match(wave5, /AudioBed landed/);
  assert.match(wave5, /Wave3 campus pack LIVE/);
  assert.match(wave5, /## Karaoke gold \(VOX-S01 PASS\)/);
  assert.match(wave5, /## Letterbox stack \(complete\)/);
  assert.match(wave5, /PR 77 `8992d0b`/);
  assert.match(wave5, /PR 65 closed SUPERSEDED, unmerged/);
  assert.match(wave5, /\*\*CLOSED\*\*, \*\*0\/8\*\*/);
  assert.match(campus, /pre-0600 status sync/);
  assert.match(campus, /audiobed-encode/);
  assert.match(campus, /9f89f9a9…/);
  assert.match(campus, /Letterbox stack complete/);
  assert.match(campus, /Wave 3 campus pack \*\*LIVE\*\*/);
  assert.match(campus, /PR 65 closed SUPERSEDED, unmerged/);
  assert.match(campus, /\*\*CLOSED\*\*, \*\*0\/8\*\*/);
  assert.match(stub, /overnight close-sync/);
  assert.match(stub, /028d16e4…/);
  assert.match(stub, /karaoke gold `9f89f9a9…`/);
  assert.match(stub, /AudioBed landed/);
  assert.match(stub, /Wave3 campus pack LIVE/);
  assert.match(stub, /audiobed-encode/);
  assert.match(gate, /Wave3 campus pack LIVE/);
  assert.match(gate, /AudioBed landed/);
  assert.match(gate, /master dest audiobed-encode/);
  assert.match(gate, /Remotion-in-Next/);
  assert.match(gate, /Cap take/);
  assert.match(gate, /Cleaning \/ Publish/);
  assert.match(gate, /AUTH_URL/);
  assert.match(gate, /Stripe/);
  assert.match(gate, /\*\*Launch is CLOSED\.\*\*/);
  assert.match(gate, /\*\*0\/8\*\*/);
  assert.doesNotMatch(wave5, /8\/8 PASS|launch OPEN|launch is open/i);
  assert.doesNotMatch(campus, /8\/8 PASS|launch OPEN|launch is open/i);
  assert.doesNotMatch(gate, /8\/8 PASS|launch OPEN|launch is open/i);
});
